def block(key: str) -> list[str]:
    """从标题 key（前缀匹配）开始，到同级或更高级标题之前的所有行（含子标题）。"""
    start = next(i for i, l in enumerate(SRC) if l.strip().startswith(key))
    level = len(HEAD.match(SRC[start]).group(1)) if HEAD.match(SRC[start]) else 1
    out = []
    for i, l in enumerate(SRC[start:]):
        m = HEAD.match(l)
        if i and m and len(m.group(1)) <= level:
            break
        out.append(l)
    return out


def sec(key: str, first: str | None = None) -> str:
    lines = [RENAME.get(l, l) for l in block(key)]
    if first is not None:
        lines[0] = first
    return "\n".join(lines).strip() + "\n"


def body(key: str) -> str:
    return "\n".join(block(key)[1:]).strip() + "\n"


def fix(text: str) -> str:
    return text  # 替换在最终文本上统一进行，见文件末尾


def list_items(key: str) -> str:
    return "\n".join(l for l in block(key) if re.match(r"^\d\. ", l)) + "\n"


